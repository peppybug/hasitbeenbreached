# One page per company, so search engines can find "has <company> been breached?".
# The report mirrors what assets/search.js draws in the browser. The risk rules are read
# straight from search.js, so both always colour data the same way.
# ---------------------------------------------------------------------------
JS = (ROOT / "assets" / "search.js").read_text(encoding="utf-8")
def js_regex(name):
    return re.compile(re.search(r"var %s = /(.*?)/i;" % name, JS).group(1), re.I)
HIGH, MED, PARTIAL = js_regex("HIGH"), js_regex("MED"), js_regex("PARTIAL")
SEV_LABEL = {"high": "High risk", "med": "Medium risk", "low": "Lower risk"}
SEV_ORDER = {"high": 0, "med": 1, "low": 2}
KIND = {"fine": "fine", "settlement": "settlement", "court": "court case", "investigation": "investigation", "order": "regulator order"}
MONTHS = "January February March April May June July August September October November December".split()

def sev(cat):
    if (PARTIAL.search(cat) and not re.search("social security", cat, re.I)) or re.search("sim card number", cat, re.I):
        return "med"
    return "high" if HIGH.search(cat) else "med" if MED.search(cat) else "low"

def fmt(d):
    p = str(d).split("-")
    return p[0] if len(p) == 1 else "%s %s" % (MONTHS[int(p[1]) - 1], p[0])

def slug(name):
    s = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode().lower()
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")

def ym(s):
    p = str(s or "").split("-")
    return int(p[0]), (int(p[1]) if len(p) > 1 else None)

def lag(b):
    if not b.get("disclosed") or not b.get("date") or b.get("timing_unclear"):
        return None
    (ay, am), (zy, zm) = ym(b["date"]), ym(b["disclosed"])
    if am and zm:
        m = (zy - ay) * 12 + (zm - am)
        text = ("the same month" if m <= 0 else "about 1 month later" if m == 1 else "about %d months later" % m if m < 12
                else "over a year later" if m < 18 else "about %d years later" % round(m / 12))
    else:
        y = zy - ay; m = y * 12
        text = "the same year" if y <= 0 else "about a year later" if y == 1 else "about %d years later" % y
    return {"months": m, "text": text, "yearly": not (am and zm), "bucket": "fast" if m <= 2 else "mid" if m < 12 else "slow"}

def lag_short(l):
    m = l["months"]
    if m <= 0: return "Same year" if l["yearly"] else "Same month"
    if m < 12: return "1 month" if m == 1 else "%d months" % m
    return "About a year" if round(m / 12) == 1 else "About %d years" % round(m / 12)

e = H.escape
def ext(text, url):
    return '<a href="%s" target="_blank" rel="noopener noreferrer">%s</a>' % (e(url), e(text))

def track(c):
    n = len(c["breaches"]); years = sorted(ym(b["date"])[0] for b in c["breaches"])
    stats = []
    def stat(label, value, sub="", cls=""):
        stats.append('<div class="tstat%s"><p class="tl">%s</p><p class="tv">%s</p>%s</div>' % (
            " " + cls if cls else "", e(label), e(value), '<p class="ts">%s</p>' % e(sub) if sub else ""))
    stat("Breaches on record", str(n), ("In %d" % years[0]) if years[0] == years[-1] else "%d to %d" % (years[0], years[-1]))
    lags = sorted(filter(None, map(lag, c["breaches"])), key=lambda l: -l["months"])
    if lags:
        stat("Longest time to make it known" if n > 1 else "Time to make it known", lag_short(lags[0]), "after the breach began", "lag-" + lags[0]["bucket"])
    else:
        stat("Time to make it known", "Unknown")
    outs = [o for b in c["breaches"] for o in b.get("outcomes") or []]
    if outs:
        counts = {}
        for o in outs: counts[o["kind"]] = counts.get(o["kind"], 0) + 1
        stat("Regulator or court action", ", ".join("%d %s%s" % (v, KIND[k], "s" if v > 1 else "") for k, v in counts.items()), "See details below", "has-action")
    else:
        stat("Regulator or court action", "None recorded", "That we know of")
    worst = min((sev(x) for b in c["breaches"] for x in b["categories"]), key=SEV_ORDER.get, default="low")
    stat("Most sensitive data exposed", SEV_LABEL[worst], "", "risk-" + worst)
    st = sum(1 for b in c["breaches"] if b.get("statement"))
    stat("Official statements", "%d of %d" % (st, n), "Company spoke publicly every time" if st == n else "Not for every breach" if st else "None found")
    return ('<section class="track" aria-label="Track record for %s"><div class="track-head"><h2 class="h4">Track record</h2>'
            '<p class="track-note">A summary of the records below. Not a security rating.</p></div><div class="track-grid">%s</div></section>') % (e(c["name"]), "".join(stats))

def entry(c, b):
    unv = b["status"] != "confirmed"
    cats = sorted(b["categories"], key=lambda x: SEV_ORDER[sev(x)])
    worst = sev(cats[0]) if cats else "low"
    risk = {"high": "High-risk data exposed", "med": "Medium-risk data exposed", "low": "Lower-risk data exposed"}[worst]
    rows = ['<div><dt>When</dt><dd>%s</dd></div>' % e(fmt(b["date"]))]
    if b.get("affected"): rows.append('<div><dt>Affected</dt><dd>%s</dd></div>' % e(b["affected"]))
    if b.get("disclosed"):
        l = lag(b)
        rows.append('<div><dt>Made known</dt><dd><span>%s%s</span></dd></div>' % (e(fmt(b["disclosed"])), '<span class="lagtag lag-%s">%s</span>' % (l["bucket"], e(l["text"])) if l else ""))
    rows.append('<div><dt>Source</dt><dd>%s</dd></div>' % e(b.get("source_name") or "Public source"))
    tags = "".join('<li class="sev-%s" title="%s"><span class="sr">%s: </span>%s</li>' % (sev(x), SEV_LABEL[sev(x)], SEV_LABEL[sev(x)], e(x)) for x in cats)
    rows.append('<div class="wide"><dt>Exposed</dt><dd><ul class="tags sev-tags">%s</ul></dd></div>' % tags)
    out = ['<div class="entry"><div class="entry-top"><h3 class="h4">%s</h3><span class="status%s">%s</span><span class="risk risk-%s">%s</span></div>' % (
        e(b["title"]), " unv" if unv else "", "Unverified report" if unv else "Confirmed", worst, risk)]
    out.append('<dl class="facts">%s</dl>' % "".join(rows))
    out.append('<p class="legend" aria-hidden="true"><span class="lg-high">High risk</span><span class="lg-med">Medium risk</span><span class="lg-low">Lower risk</span></p>')
    if unv: out.append('<p class="caveat">This comes from a report that has not been confirmed. Treat it with care.</p>')
    out.append('<p class="plain">%s</p>' % e(b["description"]))
    if b.get("outcomes"):
        lis = "".join('<li class="oc-%s"><span class="okind">%s · %s</span><span class="otext">%s</span>%s</li>' % (
            o["kind"], KIND[o["kind"]], o["year"], e(o["text"]), " " + ext("Decision", o["url"]) if o.get("url") else "") for o in b["outcomes"])
        out.append('<div class="outcomes"><p class="ol">What happened next</p><ul>%s</ul></div>' % lis)
    st = b.get("statement")
    if st:
        out.append('<div class="statement"><p class="st-label">Official statement from %s</p><p class="st-link">%s</p></div>' % (e(c["name"]), ext(st["title"], st["url"])))
    else:
        out.append('<div class="statement none"><p class="st-label">No official company statement found</p><p class="st-none">We couldn’t find a public statement from the company about this breach. The record is based on the source below.</p></div>')
    if not (st and st["url"] == b["source_url"]) and b["source_url"].startswith("https://"):
        out.append('<p class="src">Source: %s</p>' % ext(b.get("source_name") or b["source_url"], b["source_url"]))
    out.append("</div>")
    return "".join(out)

def nice_date(d):
    y, m, day = d.split("-")
    return "%d %s %s" % (int(day), MONTHS[int(m) - 1], y)

def plural(n, word):
    return "%d %s%s" % (n, word, "" if n == 1 else "es" if word.endswith("ch") else "s")

DATA = json.loads((ROOT / "data" / "breaches.json").read_text(encoding="utf-8"))
COMPANIES = sorted(DATA["companies"], key=lambda c: c["name"].lower())
seen = {}
for c in COMPANIES:
    s = slug(c["name"]); assert s not in seen, "two companies share the address company/%s" % s; seen[s] = c

SEARCH_BOX = ('<form class="search co-search" action="./" method="get" role="search" aria-label="Company search">'
              '<label for="q" class="sr">Company name or website</label>'
              '<input id="q" name="q" type="search" placeholder="Check another company" autocomplete="off" minlength="2" maxlength="100" required>'
              '<button class="btn" type="submit">Check history</button></form>')

def write_page(out, title, description, body, src, head_title=None):
    social = SOCIAL % ((BASE + out[:-5],) * 2 + ((head_title or title) + " – Has it been Breached?", description))
    nav = "".join('<li%s><a href="%s">%s</a></li>' % (' class="hide-sm"' if h == "sources.html" else "", h, l) for h, l in NAV)
    page = TEMPLATE.format(title=e(head_title or title), description=e(description), nav=nav, body=body, src=src, social=social)
    page = page.replace('<meta charset="utf-8">\n', '<meta charset="utf-8">\n<base href="/">\n', 1)
    page = page.replace('<link rel="stylesheet" href="assets/site.css?v=6">', '<link rel="stylesheet" href="assets/site.css?v=6">\n<link rel="stylesheet" href="assets/home.css?v=15">', 1)
    page = page.replace('<main id="main"><div class="wrap narrow">', '<main id="main" class="co-main"><div class="wrap narrow">', 1)
    path = ROOT / out; path.parent.mkdir(exist_ok=True); path.write_text(page, encoding="utf-8")

(ROOT / "company").mkdir(exist_ok=True)
for old in (ROOT / "company").glob("*.html"):
    if old.stem not in seen: old.unlink()
for s, c in seen.items():
    n = len(c["breaches"]); years = sorted(ym(b["date"])[0] for b in c["breaches"])
    span = ("in %d" % years[0]) if years and years[0] == years[-1] else ("between %d and %d" % (years[0], years[-1])) if years else ""
    if n:
        lead = "%s has %s on public record, %s. See what was exposed, how long it took to be made known, and what happened next. Every record links to its source." % (c["name"], plural(n, "data breach"), span)
        desc = "%s data breach history: %s on record (%s). What was exposed, when it was made known and what happened next, with official sources." % (c["name"], plural(n, "breach"), span.replace("in ", "").replace("between ", "").replace(" and ", " to "))
    else:
        lead = desc = "%s has no breach records in our database. That doesn’t mean it has never had one." % c["name"]
    aka = '<p class="aka">Also known as %s</p>' % e(", ".join(c["aliases"])) if c["aliases"] else ""
    report = '<article class="result" aria-label="Breach history for %s"><div class="result-head">%s%s</div><div class="result-body">%s<p class="fix"><a href="contact.html">Report a mistake in this record</a></p></div></article>' % (
        e(c["name"]), aka, track(c) if n else "", "".join(entry(c, b) for b in c["breaches"]))
    body = ('<nav class="crumbs" aria-label="Breadcrumb"><a href="./">Home</a> <span aria-hidden="true">›</span> <a href="companies.html">All companies</a> <span aria-hidden="true">›</span> <span aria-current="page">%s</span></nav>\n'
            '<h1>Has %s been breached?</h1>\n<p class="lead">%s</p>\n<p class="co-site">Website: %s · Records checked %s</p>\n<div class="co-report">%s</div>\n%s') % (
        e(c["name"]), e(c["name"]), e(lead), e(c["website"]), e(nice_date(DATA["updated"])), report, SEARCH_BOX)
    write_page("company/%s.html" % s, "Has %s been breached?" % c["name"], desc, body, "data/breaches.json", head_title="%s data breach history" % c["name"])
print("built %d company pages" % len(seen))


"""Builds the inner pages (about, sources, contact, privacy, terms, 404) from one shared template.

Edit the page text in tools/pages/*.html, then run:  python3 tools/build_pages.py
The home page (index.html) is edited directly.
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGES = ROOT / "tools" / "pages"

NAV = [("about.html", "About"), ("sources.html", "Data sources"), ("contact.html", "Contact")]

TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{title} – Has it been Breached?</title>
<meta name="description" content="{description}">
<meta name="theme-color" content="#F0F0F0">
<link rel="icon" href="favicon.ico?v=2" sizes="48x48">
<link rel="icon" href="assets/favicon.svg?v=2" type="image/svg+xml">
<link rel="apple-touch-icon" href="apple-touch-icon.png?v=2">
{social}<link rel="preload" href="assets/fonts/bricolage-grotesque-latin.woff2" as="font" type="font/woff2" crossorigin>
<link rel="preload" href="assets/fonts/figtree-latin.woff2" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="assets/site.css?v=6">
</head>
<body>
<!-- Generated by tools/build_pages.py from tools/pages/{src}. Edit that file, not this one. -->
<a class="skip" href="#main">Skip to content</a>
<header class="site"><div class="wrap bar">
  <a class="logo" href="./" aria-label="Has it been Breached? home"><i aria-hidden="true">?</i><span>Has it been Breached?</span></a>
  <nav aria-label="Main"><ul>{nav}<li><a class="btn sm" href="./#search">Search</a></li></ul></nav>
</div></header>
<main id="main"><div class="wrap narrow">
{body}
</div></main>
<footer class="site"><div class="wrap">
  <div class="foot">
    <div><a class="logo" href="./" aria-label="Has it been Breached? home"><i aria-hidden="true">?</i><span>Has it been Breached?</span></a><p class="tag">Before you trust them with your data, check their history.</p></div>
    <div><h2>Product</h2><ul><li><a href="./#how">How it works</a></li><li><a href="./#all">Browse companies</a></li><li><a href="./#faq">FAQ</a></li></ul></div>
    <div><h2>Company</h2><ul><li><a href="about.html">About</a></li><li><a href="contact.html">Contact</a></li><li><a href="sources.html">Data sources</a></li><li><a class="kofi-foot" href="https://ko-fi.com/hasitbeenbreached" target="_blank" rel="noopener">Support us on Ko-fi</a></li></ul></div>
    <div><h2>Legal</h2><ul><li><a href="privacy.html">Privacy policy</a></li><li><a href="terms.html">Terms of use</a></li></ul></div>
  </div>
  <p class="fine">© 2026 Has it been Breached? Records are based on public sources and may be incomplete or out of date. Not legal, financial or security advice.</p>
</div></footer>
</body>
</html>
"""

BASE = "https://hasitbeenbreached.com/"
SOCIAL = ("<link rel=\"canonical\" href=\"%s\">\n<meta property=\"og:type\" content=\"website\">\n<meta property=\"og:site_name\" content=\"Has it been Breached?\">\n<meta property=\"og:url\" content=\"%s\">\n<meta property=\"og:title\" content=\"%s\">\n<meta property=\"og:description\" content=\"%s\">\n<meta property=\"og:image\" content=\"" + BASE + "assets/og-image.png\">\n<meta property=\"og:image:width\" content=\"1200\">\n<meta property=\"og:image:height\" content=\"630\">\n<meta property=\"og:image:alt\" content=\"Has it been Breached? Before you share, check their history.\">\n<meta name=\"twitter:card\" content=\"summary_large_image\">\n")

for src in sorted(PAGES.glob("*.html")):
    text = src.read_text(encoding="utf-8")
    meta = dict(re.findall(r"^<!--\s*(\w+):\s*(.*?)\s*-->$", text, flags=re.M))
    body = re.sub(r"^<!--\s*\w+:.*?-->\n", "", text, flags=re.M).strip()
    out = src.name
    current = ' aria-current="page"'
    nav = "".join(
        '<li%s><a href="%s"%s>%s</a></li>' % (' class="hide-sm"' if href == "sources.html" else "", href, current if href == out else "", label)
        for href, label in NAV
    )
    social = "" if out == "404.html" else SOCIAL % ((BASE + out[:-5],) * 2 + (meta["title"] + " – Has it been Breached?", meta["description"]))
    html = TEMPLATE.format(title=meta["title"], description=meta["description"], nav=nav, body=body, src=src.name, social=social)
    if out == "404.html":
        # Missing pages show 404.html at whatever bad address was requested, even deep ones like /a/b/c.
        # A <base> makes styles, scripts and links resolve from the site root.
        base = '<base href="/">\n'
        html = html.replace('<meta charset="utf-8">\n', '<meta charset="utf-8">\n' + base, 1)
        html = html.replace('<main id="main"><div class="wrap narrow">', '<main id="main" class="nf-main"><div class="wrap">', 1)
    (ROOT / out).write_text(html, encoding="utf-8")
    print("built", out)

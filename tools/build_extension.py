"""Prepares the browser extension in extension/ and packs it as a zip for the Chrome Web Store.

- Copies the risk rules from assets/search.js into extension/sev.js, so the extension and the site
  always colour exposed data the same way.
- Bundles the current data/breaches.json as a fallback (the extension downloads a fresh copy daily).

Run from the repository root:  python3 tools/build_extension.py [path/to/output.zip]
"""
import json, pathlib, re, shutil, sys, zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXT = ROOT / "extension"
JS = (ROOT / "assets" / "search.js").read_text(encoding="utf-8")

def grab(pattern):
    m = re.search(pattern, JS, re.S)
    assert m, "could not find %r in assets/search.js" % pattern
    return m.group(0)

sev_js = (
    "// Generated by tools/build_extension.py from assets/search.js. Edit the rules there, not here.\n"
    + grab(r"var HIGH = /.*?/i;") + "\n"
    + grab(r"var MED = /.*?/i;") + "\n"
    + grab(r"var PARTIAL = /.*?/i;") + "\n"
    + "export " + grab(r"function sev\(cat\) \{.*?\n")
    + "export const SEV_ORDER = { high: 0, med: 1, low: 2 };\n"
)
(EXT / "sev.js").write_text(sev_js, encoding="utf-8")

(EXT / "data").mkdir(exist_ok=True)
shutil.copyfile(ROOT / "data" / "breaches.json", EXT / "data" / "breaches.json")

manifest = json.loads((EXT / "manifest.json").read_text(encoding="utf-8"))
companies = len(json.loads((EXT / "data" / "breaches.json").read_text(encoding="utf-8"))["companies"])
print("extension %s ready with %d companies" % (manifest["version"], companies))

if len(sys.argv) > 1:
    out = pathlib.Path(sys.argv[1])
    skip = {"STORE_LISTING.md"}
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(EXT.rglob("*")):
            if f.is_file() and f.name not in skip:
                z.write(f, f.relative_to(EXT).as_posix())
    print("packed", out)
